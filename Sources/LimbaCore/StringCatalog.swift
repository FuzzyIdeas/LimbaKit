import Foundation

/// The parts of Xcode's String Catalog (`.xcstrings`) that the protocol reads.
public struct StringCatalog: Codable, Sendable {
    public var sourceLanguage: String
    public var version: String?
    public var strings: [String: Entry]

    public struct Entry: Codable, Sendable {
        public var comment: String?
        public var isCommentAutoGenerated: Bool?
        public var extractionState: String?
        public var shouldTranslate: Bool?
        public var localizations: [String: Localization]?
    }

    public struct Localization: Codable, Sendable {
        public var stringUnit: StringUnit?
        public var variations: Variations?
        public var substitutions: [String: Substitution]?
    }

    public struct StringUnit: Codable, Sendable {
        public var state: String?
        public var value: String
    }

    public struct Variations: Codable, Sendable {
        public var plural: [String: Variation]?
        public var device: [String: Variation]?
    }

    public struct Variation: Codable, Sendable {
        public var stringUnit: StringUnit?
        public var variations: Variations?
    }

    public struct Substitution: Codable, Sendable {
        public var argNum: Int?
        public var formatSpecifier: String?
        public var variations: Variations?
    }

    public static func load(_ url: URL) throws -> StringCatalog {
        try JSONDecoder().decode(StringCatalog.self, from: Data(contentsOf: url))
    }
}

/// One string an app shows, as a translator sees it.
public struct SourceString: Codable, Sendable, Hashable, Identifiable {
    public var table: String
    public var key: String
    /// The text in the source language. For a plural string, its `other` form.
    public var text: String
    /// Plural forms in the source language, by CLDR category, when the developer added them.
    public var plural: [String: String]?
    public var comment: String?
    public var translate: Bool
    /// True for keys that the app looked up at runtime but that no catalog contains.
    public var discovered: Bool

    public var id: String { SourceString.id(table: table, key: key) }

    public static func id(table: String, key: String) -> String { "\(table)\u{1F}\(key)" }

    public init(table: String, key: String, text: String, plural: [String: String]? = nil, comment: String? = nil, translate: Bool = true, discovered: Bool = false) {
        self.table = table
        self.key = key
        self.text = text
        self.plural = plural
        self.comment = comment
        self.translate = translate
        self.discovered = discovered
    }
}

public extension StringCatalog {
    /// Translatable strings in this catalog, sorted by key. Stale entries and empty keys are skipped.
    func sourceStrings(table: String) -> [SourceString] {
        strings.compactMap { key, entry -> SourceString? in
            guard !key.isEmpty, entry.extractionState != "stale" else { return nil }
            let loc = entry.localizations?[sourceLanguage]
            var plural: [String: String]?
            if let forms = loc?.variations?.plural {
                plural = forms.compactMapValues { $0.stringUnit?.value }
            }
            let text = loc?.stringUnit?.value ?? plural?["other"] ?? key
            // A key with no letters ("-", "%@", "•") has nothing to translate.
            let translate = (entry.shouldTranslate ?? true) && text.contains(where: \.isLetter)
            return SourceString(table: table, key: key, text: text, plural: plural, comment: entry.comment, translate: translate)
        }
        .sorted { $0.key.localizedStandardCompare($1.key) == .orderedAscending }
    }
}
